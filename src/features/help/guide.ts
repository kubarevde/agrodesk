export function getGuideStepsForUser(
  role: CurrentUser['role'],
  allowedSections: string[] | undefined,
): GuideStep[] {
  const isAdmin = role === 'admin'
  const sections = allowedSections ?? []

  return COMMON_STEPS.filter((step) => {
    if (step.roles && !step.roles.includes(role)) return false
    if (!step.section) return true
    if (isAdmin) return true
    if (step.section === 'my-shift') return true
    if (sections.length === 0) return true
    return sections.includes(step.section)
  })
}

/** Resolve ?section= alias or step id to an index in the filtered steps list. */
export function findGuideStepIndex(
  steps: GuideStep[],
  sectionOrId: string | undefined,
): number {
  if (!sectionOrId) return -1
  const key = GUIDE_SECTION_ALIASES[sectionOrId] ?? sectionOrId
  return steps.findIndex(
    (step) => step.id === key || step.section === sectionOrId || step.id === sectionOrId,
  )
}

/** Stable ids that should always exist in the raw catalog (content regression guard). */
export const GUIDE_CATALOG_IDS = COMMON_STEPS.map((s) => s.id)
