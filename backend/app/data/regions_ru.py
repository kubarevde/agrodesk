def normalize_region_code(value: str | None) -> str | None:
    if value is None:
        return None
    code = value.strip()
    if not code:
        return None
    if code not in RU_REGION_CODES:
        raise ValueError(f'Unknown region code: {code}')
    return code


def region_label(code: str | None) -> str | None:
    if not code:
        return None
    return RU_REGION_LABEL_BY_CODE.get(code)
